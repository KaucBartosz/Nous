// Enables "Silent download" in Settings (without it the native OS dialog
// blocks export tests). Idempotent across runs.
async function enableSilentDownloads() {
  await page.click('#nav-settings');
  await expect(page.locator('#settings-view')).toBeVisible();
  // The switch input has zero size (CSS .switch) — read state via property,
  // click the visible slider like a real user.
  await expect(page.locator('#download-settings-section')).toBeVisible();
  await page.locator('#download-settings-section').scrollIntoViewIfNeeded();
  const toggle = page.locator('#silent-download-toggle');
  // Keyed by the toggle input (not the localized title) — locale-safe selector.
  const slider = page.locator('label.switch:has(#silent-download-toggle)');
  if (!(await toggle.isChecked())) {
    await slider.click();
  }
  // Download dir path may not be present in DOM; just ensure toggle is checked
  await expect(toggle).toBeChecked();
}

