test.describe('Electron App - CSV Export (historyExport)', () => {
  // Seeds a plain (unencrypted) guest result directly into IndexedDB.
  // Fixed id = idempotent across runs (put overwrites).
  async function seedGuestResult() {
    await page.evaluate(() => new Promise((resolve, reject) => {
      const open = indexedDB.open('NousDB');
      open.onsuccess = () => {
        const db = open.result;
        const now = new Date().toISOString();
        const tx = db.transaction('results', 'readwrite');
        tx.objectStore('results').put({
          id: 'e2e-seed-csv-1',
          test_id: 'stroop',
          timestamp: now,
          created_at: now,
          subject_id: 'P1',
          researcher_uid: 'GUEST',
          wyniki: { score: 5 },
          sync_status: 'LOCAL',
        });
        tx.oncomplete = () => resolve(true);
        tx.onerror = () => reject(tx.error);
      };
      open.onerror = () => reject(open.error);
    }));
  }

  test('CSV export of the current view saves a file with data', async () => {
    await loginAsGuest();
    await enableSilentDownloads();
    await seedGuestResult();

    await page.click('#nav-history');
    await expect(page.locator('#history-view')).toBeVisible();
    // The table renders the seeded row (3/3 split in the live app)
    await expect(page.locator('#history-view td', { hasText: 'stroop' }).first())
      .toBeVisible({ timeout: 15000 });

    // Electron does not emit a 'download' event to Playwright — assert on the file.
    // (downloadFile() is a plain Blob + anchor, no system dialog.)
    const downloadsDir = await electronApp.evaluate(({ app }) => app.getPath('downloads'))
      .catch(() => path.join(os.homedir(), 'Downloads'));
    const csvPath = path.join(downloadsDir, 'historia_wynikow.csv');
    await rm(csvPath, { force: true });

    await page.click('#btn-export-csv');
    await expect.poll(async () => {
      try {
        await stat(csvPath);
        return true;
      } catch {
        return false;
      }
    }, { timeout: 15000 }).toBe(true);

    const content = await readFile(csvPath, 'utf-8');
    // Matrix CSV of the current view (header = union of keys)
    expect(content).toContain('Test ID');
    expect(content).toContain('stroop');
    expect(content).toContain('P1');
    await rm(csvPath, { force: true });
  });

  test('ZIP export in silent mode saves to Downloads (no dialog)', async () => {
    await loginAsGuest();
    await enableSilentDownloads();
    await seedGuestResult();

    await page.click('#nav-history');
    await expect(page.locator('#history-view')).toBeVisible();
    await expect(page.locator('#history-view td', { hasText: 'stroop' }).first())
      .toBeVisible({ timeout: 15000 });

    const downloadsDir = await electronApp.evaluate(({ app }) => app.getPath('downloads'))
      .catch(() => path.join(os.homedir(), 'Downloads'));
    const zipsBefore = new Set(
      (await readdir(downloadsDir)).filter((f) => f.endsWith('.zip')),
    );

    // handleDownloadAllLocal('GUEST') → bulkZip → silent save, no dialog.
    await page.click('#btn-local-download-all');

    let newZip = null;
    await expect.poll(async () => {
      const after = (await readdir(downloadsDir)).filter((f) => f.endsWith('.zip'));
      newZip = after.find((f) => !zipsBefore.has(f) && f.startsWith('Wyniki_')) || null;
      return newZip;
    }, { timeout: 20000 }).not.toBeNull();

    const zipStat = await stat(path.join(downloadsDir, newZip));
    expect(zipStat.size).toBeGreaterThan(0);
    // The button animation stops when done (restore ~1 s).
    await expect(page.locator('#btn-local-download-all')).toBeEnabled({ timeout: 10000 });
    await expect(page.locator('#btn-local-download-all.downloading')).toHaveCount(0);
    await rm(path.join(downloadsDir, newZip), { force: true });
  });
});

